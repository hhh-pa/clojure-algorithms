(ns clojure-algorithms.maths.keith-number
  "== Keith Number (Repfigit Number) ==
A Keith number (also known as a repfigit number, short for \"repetitive
Fibonacci-like digit\") is a natural number n with d >= 2 decimal digits
such that when a sequence is formed starting with the d digits of n and each
subsequent term is the sum of the preceding d terms, the number n itself
appears in the sequence.

References:
- https://en.wikipedia.org/wiki/Keith_number
- https://oeis.org/A007629")

(defn is-keith-number
  "Check whether the integer number is a Keith number: an integer >= 10
  that appears in the Fibonacci-like sequence generated by its own digits.
  Throws :TypeError when number is not an integer."
  [number]
  (when (or (not (integer? number)) (boolean? number))
    (throw (ex-info "number must be an integer" {:type :TypeError})))
  (if (< number 10)
    false
    (let [digits (mapv #(Character/digit ^char % 10) (str number))]
      (loop [window digits
             current-sum (reduce +' digits)]
        (if (>= current-sum number)
          (== current-sum number)
          (recur (conj (vec (rest window)) current-sum)
                 (-' (*' 2 current-sum) (first window))))))))

(defn find-keith-numbers
  "Find and return all Keith numbers up to limit (inclusive).
  Throws :TypeError when limit is not an integer and :ValueError when
  limit is less than 10."
  [limit]
  (when (or (not (integer? limit)) (boolean? limit))
    (throw (ex-info "limit must be an integer" {:type :TypeError})))
  (when (< limit 10)
    (throw (ex-info "limit must be an integer greater than or equal to 10"
                    {:type :ValueError})))
  (vec (filter is-keith-number (range 10 (inc limit)))))
