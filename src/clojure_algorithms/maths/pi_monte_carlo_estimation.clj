(defrecord Point [x y])

(defn make-Point "Constructor for Point."
  [x y] (let [self (atom {})] (try (swap! self (fn [__c] (py-assoc-in __c [:x] x))) (swap! self (fn [__c] (py-assoc-in __c [:y] y))) (catch clojure.lang.ExceptionInfo __e (if (:__return__ (ex-data __e)) nil (throw __e)))) (map->Point @self)))

(defn Point-is-in-unit-circle "True, if the point lies in the unit circle\nFalse, otherwise"
  [self] (py-le (py-add (py-pow (:x @self) 2) (py-pow (:y @self) 2)) 1))

