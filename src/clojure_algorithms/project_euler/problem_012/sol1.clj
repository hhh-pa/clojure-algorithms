(ns clojure-algorithms.project-euler.problem-012.sol1
  "Project Euler Problem 12: highly divisible triangular number.

  The sequence of triangle numbers is generated by adding the natural
  numbers. So the 7th triangle number would be
  1 + 2 + 3 + 4 + 5 + 6 + 7 = 28.

  We can see that 28 is the first triangle number to have over five
  divisors. What is the value of the first triangle number to have over
  five hundred divisors?")

(defn count-divisors
  "Returns the number of divisors of n, computed from the prime-factor
  multiplicities."
  [n]
  (loop [n n i 2 acc 1]
    (if (> (* i i) n)
      (if (> n 1) (* acc 2) acc)
      (let [[n multiplicity] (loop [n n m 0]
                               (if (zero? (mod n i))
                                 (recur (quot n i) (inc m))
                                 [n m]))]
        (recur n (inc i) (* acc (inc multiplicity)))))))

(defn solution
  "Returns the value of the first triangle number to have over target
  divisors (500 by default)."
  ([] (solution 500))
  ([target]
   (loop [t-num 1 i 1]
     (let [i (inc i)
           t-num (+ t-num i)]
       (if (> (count-divisors t-num) target)
         t-num
         (recur t-num i))))))
